#!/usr/bin/env python3
"""Generates THIRD-PARTY-NOTICES.txt from notices/components.json, and gates it.

The notices file credits every third-party component whose code ships inside the Quantix
package. It is generated, never hand-edited: the inputs are notices/components.json and the
verbatim licence texts under notices/licenses/.

    python3 eng/notices.py           # regenerate THIRD-PARTY-NOTICES.txt
    python3 eng/notices.py --check   # fail if the inputs or the committed file have drifted

The check fails when:
  * a PackageVersion in Directory.Packages.props is not classified in components.json as
    'bundled' or 'not-distributed' (a new dependency must be decided on, not slip through);
  * components.json lists a package that Directory.Packages.props no longer pins;
  * a bundled package's pinned version differs from the version its notice credits;
  * a licence file is missing, or THIRD-PARTY-NOTICES.txt differs from the generated text.
"""

import json
import os
import sys
import xml.etree.ElementTree as ElementTree

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTICES_DIR = os.path.join(ROOT, "notices")
COMPONENTS = os.path.join(NOTICES_DIR, "components.json")
PACKAGES_PROPS = os.path.join(ROOT, "Directory.Packages.props")
OUTPUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.txt")

RULE = "=" * 78


def read_pinned_versions():
    """Returns {package id: version} from the central package versions file."""
    tree = ElementTree.parse(PACKAGES_PROPS)
    return {
        element.get("Include"): element.get("Version")
        for element in tree.iter("PackageVersion")
    }


def validate(components, pinned):
    """Returns a list of human-readable problems with the inputs; empty when they are sound."""
    problems = []
    packages = components["packages"]
    notices = components["notices"]

    for package_id, version in sorted(pinned.items()):
        entry = packages.get(package_id)
        if entry is None:
            problems.append(
                f"{package_id} {version} is pinned but not classified in notices/components.json "
                "(add it as 'bundled' with a notice, or 'not-distributed' with the reason).")
            continue

        if entry.get("distribution") not in ("bundled", "not-distributed"):
            problems.append(f"{package_id}: distribution must be 'bundled' or 'not-distributed'.")
        elif entry["distribution"] == "bundled":
            if entry.get("version") != version:
                problems.append(
                    f"{package_id} is pinned at {version} but classified at {entry.get('version')}; "
                    "re-fetch its licence for the new version and update components.json.")
            if not any(n["component"] == package_id and n["version"] == version for n in notices):
                problems.append(f"{package_id} {version} is bundled but has no matching notice.")

    for package_id in sorted(set(packages) - set(pinned)):
        problems.append(f"{package_id} is classified in components.json but no longer pinned; remove it.")

    for notice in notices:
        if not os.path.isfile(os.path.join(NOTICES_DIR, notice["licenseFile"])):
            problems.append(f"Licence file notices/{notice['licenseFile']} is missing.")

    return problems


def render(components):
    """Renders the notices text. Deterministic: depends only on the committed inputs."""
    lines = [
        "THIRD-PARTY SOFTWARE NOTICES",
        "",
        "Quantix is licensed under the Apache License, Version 2.0 (see LICENSE).",
        "",
        "The Quantix package includes the third-party components listed below. Each is",
        "distributed under its own licence, reproduced in full after its entry.",
        "",
        "This file is generated by eng/notices.py from notices/components.json.",
        "Do not edit it by hand.",
    ]

    for notice in components["notices"]:
        with open(os.path.join(NOTICES_DIR, notice["licenseFile"]), encoding="utf-8-sig") as handle:
            licence_text = handle.read().strip("\n")

        lines += [
            "",
            RULE,
            notice["component"],
            RULE,
            f"Version:  {notice['version']}",
            f"Licence:  {notice['license']}",
            f"Project:  {notice['project']}",
            f"Usage:    {notice['usage']}",
            f"Source:   {notice['licenseSource']} (retrieved {notice['retrieved']})",
            "",
            licence_text,
        ]

    return "\n".join(lines) + "\n"


def main(argv):
    check = "--check" in argv

    with open(COMPONENTS, encoding="utf-8") as handle:
        components = json.load(handle)

    problems = validate(components, read_pinned_versions())
    if problems:
        for problem in problems:
            print(f"notices: {problem}", file=sys.stderr)
        return 1

    expected = render(components)

    if check:
        try:
            with open(OUTPUT, encoding="utf-8", newline="") as handle:
                actual = handle.read()
        except FileNotFoundError:
            actual = None

        if actual != expected:
            print("notices: THIRD-PARTY-NOTICES.txt is out of date; run 'python3 eng/notices.py'.",
                  file=sys.stderr)
            return 1

        print("notices: THIRD-PARTY-NOTICES.txt is up to date.")
        return 0

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(expected)

    print(f"notices: wrote {os.path.relpath(OUTPUT, ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
